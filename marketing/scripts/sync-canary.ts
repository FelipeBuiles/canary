import { execFileSync } from 'node:child_process'
import { lstatSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import type { CanaryLock } from '../src/domain.ts'
import { CANARY_ROOT, loadLock, loadManifest, PATHS, readCanary, ROOT, sha256 } from '../src/workspace.ts'

function isMissing(e: unknown): boolean {
  return e instanceof Error && 'code' in e && e.code === 'ENOENT'
}

// existsSync reports a dangling symlink as absent, and writeFileSync would then follow it out of the workspace.
function assertWritableOutput(root: string, path: string): void {
  let cursor = resolve(root)
  const parts = path.split('/')
  for (const [i, part] of parts.entries()) {
    cursor = join(cursor, part)
    let stat
    try {
      stat = lstatSync(cursor)
    } catch (e) {
      if (isMissing(e) && i === parts.length - 1) return
      throw new Error(`cannot write ${path}: ${isMissing(e) ? 'parent directory missing' : String(e)}`)
    }
    if (stat.isSymbolicLink()) throw new Error(`refusing to write through symlink: ${path}`)
    if (i < parts.length - 1 ? !stat.isDirectory() : !stat.isFile()) throw new Error(`not a regular output path: ${path}`)
  }
}

function sameFiles(a: Record<string, string>, b: Record<string, string>): boolean {
  const keys = Object.keys(a)
  return keys.length === Object.keys(b).length && keys.every((k) => a[k] === b[k])
}

export function syncCanary({ root = ROOT, canaryRoot = CANARY_ROOT }: { root?: string; canaryRoot?: string } = {}): string {
  const loaded = loadManifest(root)
  if (!loaded.manifest) throw new Error(loaded.errors.map((e) => `${e.path}: ${e.message}`).join('; '))
  const manifest = loaded.manifest
  for (const path of [PATHS.lock, PATHS.changes]) assertWritableOutput(root, path)
  const prior = loadLock(root)
  const lockMissing = prior.errors.some((e) => e.message.includes('lock missing'))
  if (prior.errors.length && !lockMissing) throw new Error(prior.errors.map((e) => `${e.path}: ${e.message}`).join('; '))
  const previous = prior.lock
  const git = (...args: string[]) => execFileSync('git', ['-C', canaryRoot, ...args], { encoding: 'utf8', maxBuffer: 64 << 20 }).trim()

  const sha = git('rev-parse', 'HEAD')
  const pathspecs = [...manifest.include.map((g) => `:(glob)${g}`), ...manifest.exclude.map((g) => `:(glob,exclude)${g}`)]
  const files = git('ls-files', '--', ...pathspecs).split('\n').filter(Boolean).sort((a, b) => a.localeCompare(b))
  const hashes = Object.fromEntries(files.map((f) => {
    const text = readCanary(f, canaryRoot)
    if (text === undefined) throw new Error(`cannot sync unreadable or unsafe canary file: ${f}`)
    return [f, sha256(text)]
  }))

  if (previous && previous.sha === sha && sameFiles(previous.files, hashes)) {
    return `canary ${sha.slice(0, 8)} unchanged: ${files.length} docs; lock and changelog kept`
  }

  const lock: CanaryLock = { sha, synced: new Date().toISOString(), files: hashes }
  const since = previous?.sha ?? git('rev-list', '-1', '--before=30 days ago', 'HEAD')
  const log = git('log', '--no-merges', '--date=short', '--format=- %ad `%h` %s', `${since}..HEAD`)
  const changedDocs = [...new Set([...Object.keys(previous?.files ?? {}), ...files])].filter((f) => previous?.files[f] !== lock.files[f])
  const changes = [
    '# Canary changes since last sync',
    '',
    `Range \`${since.slice(0, 8)}..${sha.slice(0, 8)}\`, synced ${lock.synced}. Generated by \`npm run sync:canary\`; do not edit.`,
    '',
    '## Commits',
    '',
    log || '_none_',
    '',
    '## Manifest docs changed',
    '',
    changedDocs.map((f) => `- ${f}${f in lock.files ? '' : ' (removed)'}`).join('\n') || '_none_',
    '',
  ].join('\n')

  writeFileSync(join(root, PATHS.lock), `${JSON.stringify(lock, null, 2)}\n`)
  writeFileSync(join(root, PATHS.changes), changes)
  return `synced canary ${sha.slice(0, 8)}: ${files.length} docs, ${changedDocs.length} changed, ${log ? log.split('\n').length : 0} commits`
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try {
    process.stdout.write(`${syncCanary()}\n`)
  } catch (e) {
    process.stderr.write(`sync: ${e instanceof Error ? e.message : String(e)}\n`)
    process.exitCode = 1
  }
}
