interface I18nValue {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (text: string) => string;
  stageName: (stage: StageName) => string;
  statusName: (status: StageStatus) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function readStoredLanguage(): LanguageCode {
  const stored = globalThis.localStorage?.getItem(STORAGE_KEY);
  return stored === "es" || stored === "fr" ? stored : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<LanguageCode>(() => readStoredLanguage());

  useEffect(() => {
    globalThis.localStorage?.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (text) => TEXT[language][text] ?? text,
    stageName: (stage) => STAGES[language][stage],
    statusName: (status) => STATUS[language][status],
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
