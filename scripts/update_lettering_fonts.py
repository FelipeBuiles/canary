#!/usr/bin/env python3
"""Generate exact Unicode coverage from bundled TTF cmap tables (no dependencies)."""

from __future__ import annotations

import argparse
import hashlib
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "novel_to_comic/src/novel_to_comic"


def codepoints(path: Path) -> set[int]:
    """Read Unicode format 4/12 cmaps, excluding mappings to the missing glyph."""
    data = path.read_bytes()

    def u16(offset: int) -> int:
        return struct.unpack_from(">H", data, offset)[0]

    def u32(offset: int) -> int:
        return struct.unpack_from(">I", data, offset)[0]

    cmap = next(
        u32(p + 8)
        for p in range(12, 12 + 16 * u16(4), 16)
        if data[p : p + 4] == b"cmap"
    )
    result: set[int] = set()
    for record in range(cmap + 4, cmap + 4 + 8 * u16(cmap + 2), 8):
        platform, encoding = u16(record), u16(record + 2)
        if platform != 0 and (platform, encoding) not in {(3, 1), (3, 10)}:
            continue
        table = cmap + u32(record + 4)
        fmt = u16(table)
        if fmt == 12:
            for group in range(table + 16, table + 16 + 12 * u32(table + 12), 12):
                start, end, glyph = struct.unpack_from(">III", data, group)
                result.update(range(start + (glyph == 0), end + 1))
        elif fmt == 4:
            count = u16(table + 6) // 2
            ends = table + 14
            starts, deltas, offsets = (
                ends + 2 * count + 2,
                ends + 4 * count + 2,
                ends + 6 * count + 2,
            )
            for index in range(count):
                start, end = u16(starts + index * 2), u16(ends + index * 2)
                delta, offset = u16(deltas + index * 2), u16(offsets + index * 2)
                for cp in range(start, min(end + 1, 0xFFFF)):
                    glyph = (
                        u16(offsets + index * 2 + offset + 2 * (cp - start))
                        if offset
                        else cp
                    )
                    if (not offset or glyph) and (glyph + delta) % 65536:
                        result.add(cp)
        elif fmt == 14:
            continue  # Variation sequences do not add stand-alone Unicode glyphs.
        else:
            raise ValueError(f"Unsupported Unicode cmap format {fmt} in {path.name}")
    if not result:
        raise ValueError(f"No usable Unicode cmap in {path}")
    return result


def base36(value: int) -> str:
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    result = ""
    while value:
        value, remainder = divmod(value, 36)
        result = digits[remainder] + result
    return result or "0"


def encoded_ranges(points: set[int]) -> str:
    ranges: list[list[int]] = []
    for cp in sorted(points):
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    previous, output = -1, []
    for start, end in ranges:
        output.append(
            base36(start - previous - 1)
            + ("." + base36(end - start) if end > start else "")
        )
        previous = end
    return ",".join(output)


def generate() -> str:
    engine = (ROOT / "lettering/engine.mjs").read_text()
    fonts = re.findall(r'"([^"]+)": "([^"]+\.ttf)"', engine)
    lines = [
        "// Generated by scripts/update_lettering_fonts.py; do not edit.",
        "// Delta/range-length pairs in base 36. Exact cmap coverage, NOT script guesses.",
        "export const FONT_COVERAGE = Object.freeze({",
    ]
    for family, filename in fonts:
        path = ROOT / "fonts" / filename
        lines.append(
            f"  // {filename} sha256:{hashlib.sha256(path.read_bytes()).hexdigest()}"
        )
        lines.append(f'  "{family}": "{encoded_ranges(codepoints(path))}",')
    return "\n".join([*lines, "});", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "lettering/font-coverage.mjs"
    generated = generate()
    if args.check:
        if not target.exists() or target.read_text() != generated:
            raise SystemExit(
                "Bundled font coverage is stale; run scripts/update_lettering_fonts.py"
            )
    else:
        target.write_text(generated)
